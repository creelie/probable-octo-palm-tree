"""Write OdaLean/Poly.lean: affine and quadratic polynomials in six integer parameters.

Usage: python3 make_poly.py OUT.lean
"""
import sys

N = 6
A = ["a%d" % i for i in range(N)]
L = ["l%d" % i for i in range(N)]
Q = [(i, j) for i in range(N) for j in range(i, N)]
QN = ["q%d%d" % ij for ij in Q]


def fields(names):
    return "\n".join("  %s : Int" % x for x in names)


def mk(name, vals):
    return "⟨%s⟩" % ", ".join(vals)


def main(out):
    w = []
    p = w.append
    p("/- Generated by generate/make_poly.py; do not edit. -/")
    p("import Mathlib.Tactic.Ring")
    p("")
    p("/-!")
    p("# Polynomials of degree at most two in six integer parameters")
    p("")
    p("An `Aff` is an affine function `c + a0 p0 + ⋯ + a5 p5` of the parameters `p : Fin 6 → ℤ`;")
    p("a `Quad` is a polynomial of degree at most two, stored by its coefficients. The products")
    p("and sums are computed on coefficients, and each `ev_*` lemma says that evaluation commutes")
    p("with the operation, so a coefficient identity is an identity for every value of `p`.")
    p("-/")
    p("")
    p("namespace Oda")
    p("")
    p("/-- Values of the six parameters. -/")
    p("abbrev Par := Fin 6 → Int")
    p("")
    p("/-- The affine function `c + a0 p0 + ⋯ + a5 p5`. -/")
    p("structure Aff where")
    p(fields(["c"] + A))
    p("deriving DecidableEq")
    p("")
    p("/-- The quadratic polynomial `c + Σ lᵢ pᵢ + Σ_{i ≤ j} qᵢⱼ pᵢ pⱼ`. -/")
    p("structure Quad where")
    p(fields(["c"] + L + QN))
    p("deriving DecidableEq")
    p("")
    p("namespace Aff")
    p("")
    p("def ev (f : Aff) (p : Par) : Int :=")
    p("  f.c + " + " + ".join("f.%s * p %d" % (a, i) for i, a in enumerate(A)))
    p("")
    p("def const (k : Int) : Aff := " + mk("", ["k"] + ["0"] * N))
    p("")
    p("def add (f g : Aff) : Aff := " + mk("", ["f.%s + g.%s" % (x, x) for x in ["c"] + A]))
    p("")
    p("def sub (f g : Aff) : Aff := " + mk("", ["f.%s - g.%s" % (x, x) for x in ["c"] + A]))
    p("")
    p("def smul (k : Int) (f : Aff) : Aff := " + mk("", ["k * f.%s" % x for x in ["c"] + A]))
    p("")
    p("/-- The coefficients of `f * g`. -/")
    p("def mul (f g : Aff) : Quad :=")
    vals = ["f.c * g.c"]
    vals += ["f.c * g.%s + f.%s * g.c" % (a, a) for a in A]
    for i, j in Q:
        if i == j:
            vals.append("f.%s * g.%s" % (A[i], A[i]))
        else:
            vals.append("f.%s * g.%s + f.%s * g.%s" % (A[i], A[j], A[j], A[i]))
    p("  " + mk("", vals))
    p("")
    p("/-- `f` does not depend on the parameters. -/")
    p("def isConst (f : Aff) : Bool := " + " && ".join("f.%s == 0" % a for a in A))
    p("")
    p("theorem ev_const (k : Int) (p : Par) : (const k).ev p = k := by simp [const, ev]")
    p("")
    for op, sym in [("add", "+"), ("sub", "-")]:
        p("theorem ev_%s (f g : Aff) (p : Par) : (%s f g).ev p = f.ev p %s g.ev p := by" % (op, op, sym))
        p("  simp only [%s, ev]; ring" % op)
        p("")
    p("theorem ev_smul (k : Int) (f : Aff) (p : Par) : (smul k f).ev p = k * f.ev p := by")
    p("  simp only [smul, ev]; ring")
    p("")
    p("theorem ev_of_isConst {f : Aff} (h : f.isConst = true) (p : Par) : f.ev p = f.c := by")
    p("  simp only [isConst, Bool.and_eq_true, beq_iff_eq] at h")
    p("  simp [ev, h]")
    p("")
    p("end Aff")
    p("")
    p("namespace Quad")
    p("")
    terms = ["q.c"] + ["q.%s * p %d" % (L[i], i) for i in range(N)]
    terms += ["q.%s * p %d * p %d" % (QN[k], i, j) for k, (i, j) in enumerate(Q)]
    p("def ev (q : Quad) (p : Par) : Int :=")
    p("  " + " + ".join(terms))
    p("")
    allq = ["c"] + L + QN
    p("def add (q r : Quad) : Quad := " + mk("", ["q.%s + r.%s" % (x, x) for x in allq]))
    p("")
    p("def sub (q r : Quad) : Quad := " + mk("", ["q.%s - r.%s" % (x, x) for x in allq]))
    p("")
    p("def smul (k : Int) (q : Quad) : Quad := " + mk("", ["k * q.%s" % x for x in allq]))
    p("")
    p("/-- `q` does not depend on the parameters. -/")
    p("def isConst (q : Quad) : Bool :=")
    p("  " + " && ".join("q.%s == 0" % x for x in L + QN))
    p("")
    for op, sym in [("add", "+"), ("sub", "-")]:
        p("theorem ev_%s (q r : Quad) (p : Par) : (%s q r).ev p = q.ev p %s r.ev p := by" % (op, op, sym))
        p("  simp only [%s, ev]; ring" % op)
        p("")
    p("theorem ev_smul (k : Int) (q : Quad) (p : Par) : (smul k q).ev p = k * q.ev p := by")
    p("  simp only [smul, ev]; ring")
    p("")
    p("theorem ev_of_isConst {q : Quad} (h : q.isConst = true) (p : Par) : q.ev p = q.c := by")
    p("  simp only [isConst, Bool.and_eq_true, beq_iff_eq] at h")
    p("  simp [ev, h]")
    p("")
    p("end Quad")
    p("")
    p("theorem Aff.ev_mul (f g : Aff) (p : Par) : (Aff.mul f g).ev p = f.ev p * g.ev p := by")
    p("  simp only [Aff.mul, Quad.ev, Aff.ev]; ring")
    p("")
    p("end Oda")
    open(out, "w").write("\n".join(w) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
