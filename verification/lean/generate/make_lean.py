"""Write the generated part of the Lean project from data/certificates.txt.

Usage: python3 make_lean.py CERTIFICATES.txt LEAN_DIR

Writes LEAN_DIR/OdaLean/Poly.lean (through make_poly.py), LEAN_DIR/OdaLean/Data/*.lean (the
certificate table as Lean lists) and LEAN_DIR/OdaLean/Cert/*.lean (one kernel-checked theorem
per block of rows).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_poly  # noqa: E402

CHUNK = 20
HEADER = "/- Generated by generate/make_lean.py from data/certificates.txt; do not edit. -/"


def cap(s):
    return s[0].upper() + s[1:]


def center(s):
    m = re.fullmatch(r"pt\((\d+),(\d+),(\d+)\)", s)
    if m:
        return "Center.pt %s %s %s" % m.groups()
    m = re.fullmatch(r"cv\((\d+),(\d+)\)", s)
    if m:
        return "Center.cv %s %s" % m.groups()
    raise ValueError(s)


def cert(kind, xs):
    if kind not in ("S", "P", "P2") or len(xs) != 3:
        raise ValueError(kind)
    return "Cert.%s ⟨%s⟩" % (kind, ", ".join(str(int(x)) for x in xs))


def read(path):
    rows = {"Z": [], "W": [], "F": [], "G": {}, "C": None}
    for line in open(path):
        t = line.split()
        if not t:
            continue
        fam = t[0]
        if fam in ("Z", "W"):
            rows[fam].append((center(t[1]), center(t[2]), cert(t[3], t[4:])))
        elif fam == "F":
            rows["F"].append((center(t[1]), cert(t[2], t[3:])))
        elif re.fullmatch(r"G[0-3]", fam):
            rows["G"][int(fam[1])] = cert(t[1], t[2:])
        elif fam == "C":
            rows["C"] = cert(t[1], t[2:])
        else:
            raise ValueError(line)
    assert sorted(rows["G"]) == [0, 1, 2, 3] and rows["C"] is not None
    return rows


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main(certs, out):
    os.makedirs(os.path.join(out, "OdaLean"), exist_ok=True)
    make_poly.main(os.path.join(out, "OdaLean", "Poly.lean"))
    rows = read(certs)
    data_imports, cert_imports = [], []
    blocks = {}
    for fam in ("Z", "W"):
        names = []
        for b in range(0, len(rows[fam]), CHUNK):
            name = "rows%s%d" % (fam, b // CHUNK)
            body = ",\n".join("  (%s, %s, %s)" % r for r in rows[fam][b:b + CHUNK])
            write(os.path.join(out, "OdaLean", "Data", cap(name) + ".lean"),
                  "%s\nimport OdaLean.Check\n\nnamespace Oda\n\ndef %s : List (Center × Center × Cert) := [\n%s]\n\nend Oda\n"
                  % (HEADER, name, body))
            data_imports.append("OdaLean.Data." + cap(name))
            names.append(name)
        blocks[fam] = names
    body = ",\n".join("  (%s, %s)" % r for r in rows["F"])
    write(os.path.join(out, "OdaLean", "Data", "RowsF.lean"),
          "%s\nimport OdaLean.Check\n\nnamespace Oda\n\ndef rowsF : List (Center × Cert) := [\n%s]\n\n"
          "def certsG : List Cert := [%s]\n\ndef certC : Cert := %s\n\nend Oda\n"
          % (HEADER, body, ", ".join(rows["G"][j] for j in range(4)), rows["C"]))
    data_imports.append("OdaLean.Data.RowsF")
    lines = [HEADER] + ["import " + m for m in data_imports] + ["", "namespace Oda", ""]
    for fam in ("Z", "W"):
        lines.append("/-- The certificates for the double blowups of `fam%s`. -/" % fam)
        lines.append("def rows%s : List (Center × Center × Cert) :=" % fam)
        lines.append("  " + " ++ ".join(blocks[fam]))
        lines.append("")
    lines.append("end Oda")
    write(os.path.join(out, "OdaLean", "Data", "All.lean"), "\n".join(lines) + "\n")
    # kernel-checked blocks
    for fam in ("Z", "W"):
        for name in blocks[fam]:
            mod = "OdaLean.Cert." + cap(name)
            write(os.path.join(out, "OdaLean", "Cert", cap(name) + ".lean"),
                  "%s\nimport OdaLean.Data.%s\n\nnamespace Oda\n\ntheorem %s_ok : %s.all (rowOK2 fam%s) = true := by\n  decide +kernel\n\nend Oda\n"
                  % (HEADER, cap(name), name, name, fam))
            cert_imports.append(mod)
    write(os.path.join(out, "OdaLean", "Cert", "Rest.lean"),
          "%s\nimport OdaLean.Data.RowsF\n\nnamespace Oda\n\n"
          "theorem rowsF_ok : rowsF.all (rowOK1 famF) = true := by\n  decide +kernel\n\n"
          "theorem certsG_ok : allN 4 (fun j => (certsG.getD j (Cert.S V3.zero)).check (famG j)) = true := by\n  decide +kernel\n\n"
          "theorem certC_ok : certC.check famC = true := by\n  decide +kernel\n\nend Oda\n" % HEADER)
    cert_imports.append("OdaLean.Cert.Rest")
    lines = [HEADER, "import OdaLean.Data.All"] + ["import " + m for m in cert_imports]
    lines += ["", "namespace Oda", ""]
    for fam in ("Z", "W"):
        lines.append("theorem rows%s_ok : rows%s.all (rowOK2 fam%s) = true := by" % (fam, fam, fam))
        lines.append("  simp only [rows%s, List.all_append, %s, Bool.and_self]"
                     % (fam, ", ".join(n + "_ok" for n in blocks[fam])))
        lines.append("")
    lines.append("end Oda")
    write(os.path.join(out, "OdaLean", "Cert", "All.lean"), "\n".join(lines) + "\n")
    print("rows: Z %d, W %d, F %d, G 4, C 1" % (len(rows["Z"]), len(rows["W"]), len(rows["F"])))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
